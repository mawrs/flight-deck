export type EdMedDisbursementStatus = "COMPLETED" | "SCHEDULED";

export interface EdMedDisbursementLine {
  date: string | null;
  amount: number | null;
  status: EdMedDisbursementStatus | null;
  fundRelease: string | null;
}

export interface EdMedDisbursementRow {
  loanNumber: string;
  updatedAt: string;
  lastName: string;
  firstName: string;
  school: string;
  loanStatus: string;
  currentYear: boolean;
  certifiedAt: string;
  daysToCertification: number;
  termMonths: number;
  rate: number;
  rateType: "FIXED";
  originalAmount: number;
  revisedAmount: number;
  disbursements: [EdMedDisbursementLine, EdMedDisbursementLine, EdMedDisbursementLine];
}

const emptyLine: EdMedDisbursementLine = {
  date: null,
  amount: null,
  status: null,
  fundRelease: null,
};

function line(
  date: string | null,
  amount: number | null,
  status: EdMedDisbursementStatus | null,
  fundRelease: string | null = date,
): EdMedDisbursementLine {
  if (!date && amount == null && !status) return emptyLine;
  return { date, amount, status, fundRelease };
}

function row(
  loanNumber: string,
  updatedAt: string,
  lastName: string,
  firstName: string,
  school: string,
  loanStatus: string,
  certifiedAt: string,
  daysToCertification: number,
  termMonths: number,
  rate: number,
  originalAmount: number,
  revisedAmount: number,
  first: EdMedDisbursementLine,
  second: EdMedDisbursementLine = emptyLine,
  third: EdMedDisbursementLine = emptyLine,
  currentYear = true,
): EdMedDisbursementRow {
  return {
    loanNumber,
    updatedAt,
    lastName,
    firstName,
    school,
    loanStatus,
    currentYear,
    certifiedAt,
    daysToCertification,
    termMonths,
    rate,
    rateType: "FIXED",
    originalAmount,
    revisedAmount,
    disbursements: [first, second, third],
  };
}

