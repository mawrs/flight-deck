export function isoToday(now = new Date()) {
  const year = now.getFullYear();
  const month = String(now.getMonth() + 1).padStart(2, "0");
  const day = String(now.getDate()).padStart(2, "0");
  return `${year}-${month}-${day}`;
}

export function scheduledToday(row: EdMedDisbursementRow, today = isoToday()) {
  return row.disbursements.some((line) => line.status === "SCHEDULED" && line.date === today);
}

export function sortEdMedRows(rows: EdMedDisbursementRow[], today = isoToday()) {
  return rows
    .map((row, index) => ({ row, index, due: scheduledToday(row, today) }))
    .sort((a, b) => Number(b.due) - Number(a.due) || a.index - b.index)
    .map((item) => item.row);
}

export function reportDate(value: string | null) {
  if (!value) return "Null";
  const [year, month, day] = value.split("-");
  return `${Number(month)}/${Number(day)}/${year}`;
}
