const SAMPLE_PDFS = [
  "Application_Disclosure.pdf",
  "Credit Score Exception Notice.pdf",
  "Degree_Verification_MSU.pdf",
  "Equifax_MLA_Verification.pdf",
  "Identity_Verification_[V1].pdf",
  "KYC_CIP_2084417.pdf",
  "Paystub_08012026.pdf",
  "Paystub_08152026.pdf",
];

function doc(id: string, caseId: string, name: string, uploadedBy: string, date: string, hour: number): CaseDocument {
  const index = Number(id.replace(/\D/g, "")) - 1;
  return {
    id,
    caseId,
    name,
    fileName: SAMPLE_PDFS[index] ?? SAMPLE_PDFS[0],
    uploadedBy,
    uploadedAt: at(date, hour),
  };
}

function loanFromCert(
  cert: Certification,
  id: string,
  servicer: ServicingLoan["servicer"],
  boardingStatus: ServicingLoan["boardingStatus"],
  boardedOn: string | null,
  principal: number,
  interest: number,
): ServicingLoan {
  return {
    id,
    certificationId: cert.id,
    applicationId: cert.applicationId,
    borrower: cert.borrower,
    product: cert.product,
    school: cert.school,
    schoolCode: cert.schoolCode,
    servicer,
    boardedAt: boardedOn ? at(boardedOn, 8) : null,
    boardingStatus,
    principal,
    interest,
    disbursements: [],
    readOnly: false,
  };
}

