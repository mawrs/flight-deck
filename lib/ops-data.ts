function at(date: string, hour = 12) {
  return `${date}T${String(hour).padStart(2, "0")}:00:00`;
}

function disb(id: string, date: string, amount: number, status: DisbursementStatus): Disbursement {
  return { id, date: at(date), amount, status };
}

function round2(value: number) {
  return Math.round(value * 100) / 100;
}

